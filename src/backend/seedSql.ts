/**
 * Builds supabase/seed.sql: the residents, their rooms, posts, threads and a
 * week of listening history, as SQL for the backend.
 *
 * It's generated from the same seed files the phone-only version uses, so the
 * seeded world has one source of truth. To regenerate after changing them:
 *
 *   npm run seed:sql
 */
import type { Track } from '@/music/types';
import { openers, residents, tastes } from '@/seed/listeners';
import { seedPosts } from '@/seed/posts';
import { seedRooms } from '@/seed/rooms';
import { seedThreads } from '@/seed/threads';
import seedTracks from '@/seed/tracks.json';

const q = (s: string | number | null | undefined) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const HOUR = 60 * 60_000;

export function buildSeedSql(): string {
  const tracks = Object.values(seedTracks as Record<string, Track>);
  const catalogue = seedTracks as Record<string, Track>;
  const homes = new Map(residents.map((r) => [r.id, r.homeCity]));
  const out: string[] = [];

  out.push(
    '-- earshot: the seeded world (generated by `npm run seed:sql`; do not edit by hand).',
    '--',
    '-- Run this in the Supabase SQL Editor AFTER supabase/schema.sql.',
    '-- It is safe to run again: it refreshes the residents and their content and',
    '-- leaves real accounts alone. Two things it does overwrite when re-run:',
    '-- residents\' rooms (including guestbook entries real people left in them)',
    '-- and replies real people added to the residents\' threads.',
    '',
  );

  out.push(
    'insert into app.tracks (id, source_id, title, artist, album, year, genre, artwork_url, preview_url) values',
    tracks
      .map((t) => `  (${[q(t.id), q(t.sourceId), q(t.title), q(t.artist), q(t.album), t.year ?? 'null', q(t.genre), q(t.artworkUrl), q(t.previewUrl)].join(', ')})`)
      .join(',\n'),
    'on conflict (id) do update set source_id = excluded.source_id, title = excluded.title, artist = excluded.artist, album = excluded.album,',
    '  year = excluded.year, genre = excluded.genre, artwork_url = excluded.artwork_url, preview_url = excluded.preview_url;',
    '',
  );

  out.push(
    '-- The residents. They have no login: they are furniture, not accounts.',
    'insert into app.profiles (id, handle, name, badge, badge_color, tagline, bio, home_city, seeded, onboarded, sharing) values',
    residents
      .map((p) => `  (${[q(p.id), q(p.handle), q(p.name), q(p.badge), q(p.badgeColor), q(p.tagline), q(p.bio), q(p.homeCity)].join(', ')}, true, true, true)`)
      .join(',\n'),
    'on conflict (id) do update set handle = excluded.handle, name = excluded.name, badge = excluded.badge, badge_color = excluded.badge_color,',
    '  tagline = excluded.tagline, bio = excluded.bio, home_city = excluded.home_city, seeded = true, onboarded = true, sharing = true;',
    '',
  );

  const tasteRows: string[] = [];
  for (const r of residents) {
    const t = tastes[r.id];
    if (!t) continue;
    for (const id of t.plays) tasteRows.push(`  (${q(r.id)}, ${q(id)}, 'play', null)`);
    for (const s of t.shares) tasteRows.push(`  (${q(r.id)}, ${q(s.trackId)}, 'share', ${q(s.note)})`);
  }
  out.push(
    'delete from app.tastes;',
    'insert into app.tastes (user_id, track_id, kind, note) values',
    tasteRows.join(',\n') + ';',
    '',
    'delete from app.openers;',
    'insert into app.openers (user_id, track_id, note, after_accept) values',
    Object.entries(openers)
      .map(([id, o]) => `  (${q(id)}, ${q(o.trackId)}, ${q(o.note)}, ${q(o.afterAccept)})`)
      .join(',\n') + ';',
    '',
  );

  out.push(
    '-- Every resident\'s room.',
    'insert into app.rooms (user_id, doc, updated_at) values',
    seedRooms.map((room) => `  (${q(room.personId)}, ${q(JSON.stringify(room))}::jsonb, app.now_ms())`).join(',\n'),
    'on conflict (user_id) do update set doc = excluded.doc, updated_at = excluded.updated_at;',
    '',
  );

  // Everything dated relative to the moment this script runs.
  const body: string[] = [];
  body.push(
    '  -- A week of listening history, so rooms have a "recently played" and cities have a chart from',
    '  -- day one. It carries a marker instead of a real area, so it never shows in Nearby.',
    "  delete from app.plays where area_id = 'history';",
    '  insert into app.plays (user_id, track_id, kind, note, area_id, started_at, ended_at) values',
  );
  const history: string[] = [];
  for (const p of residents) {
    const plays = tastes[p.id]?.plays ?? [];
    for (let i = 0; i < plays.length * 2; i++) {
      const ago = (3 + ((p.id.charCodeAt(0) * 7 + i * 19) % 150)) * HOUR + i * 240_000;
      history.push(`    (${q(p.id)}, ${q(plays[i % plays.length])}, 'play', null, 'history', at - ${ago}, at - ${ago - 200_000})`);
    }
  }
  body.push(history.join(',\n') + ';', '');

  body.push(
    '  -- The city boards. A few posts are dated forward, so they turn up while people are using the app.',
    '  delete from app.posts where seeded;',
    '  insert into app.posts (user_id, track_id, note, city, created_at, seeded) values',
    seedPosts
      .map((p) => `    (${q(p.by)}, ${q(p.trackId)}, ${q(p.note)}, ${q(homes.get(p.by) ?? 'Toronto')}, at - ${p.minutesAgo * 60_000}, true)`)
      .join(',\n') + ';',
    '',
    '  -- Artists\' rooms.',
    '  delete from app.threads where seeded;',
  );
  for (const th of seedThreads) {
    const artist = catalogue[th.artistOf]?.artist;
    if (!artist) continue;
    const started = th.daysAgo * 24 * HOUR;
    body.push(
      '  insert into app.threads (artist_key, artist, city, user_id, title, body, created_at, seeded)',
      `    values (${q(artist.toLowerCase())}, ${q(artist)}, ${q(homes.get(th.by) ?? 'Toronto')}, ${q(th.by)}, ${q(th.title)}, ${q(th.body)}, at - ${started}, true)`,
      '    returning id into tid;',
      '  insert into app.replies (thread_id, user_id, body, track_id, created_at, seeded) values',
      th.replies
        .map((r) => {
          const when = r.inMinutes !== undefined ? `at + ${r.inMinutes * 60_000}` : `least(at - 60000, at - ${started} + ${(r.after ?? 1) * HOUR})`;
          return `    (tid, ${q(r.by)}, ${q(r.body)}, ${q(r.trackId)}, ${when}, true)`;
        })
        .join(',\n') + ';',
    );
  }

  out.push('do $seed$', 'declare at bigint := app.now_ms(); tid bigint;', 'begin', ...body, 'end $seed$;', '');
  return out.join('\n');
}
